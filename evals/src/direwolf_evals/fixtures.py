"""Fixture loading: data in, provenance recorded, nothing executed.

Every fixture states where it came from. The classes are fixed, because "where
did this test data come from" is a question with a small number of honest
answers and an unbounded number of dishonest ones:

``authored``
    Written for DireWolf, deterministic, reviewed.
``protocol-adversarial``
    Hostile protocol inputs, i.e. the shared vectors in ``tests/protocol``.
``synthetic-mutation``
    Generated by mutating an authored fixture under a recorded seed.
``recorded-response``
    A captured model response, for replay. Test-only; never a provider.
``external-corpus``
    An excerpt of third-party material. Requires ``source``, ``licence`` and a
    note of any modification, and is only admissible when redistribution is
    permitted.

Fixtures are read with ``json.loads``: no YAML tags, no ``pickle``, no ``eval``,
no import hooks. A fixture is data, and a fixture that could run would be a
second execution path (the thing this whole architecture exists to prevent).
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

__all__ = ["PROVENANCE_CLASSES", "Fixture", "FixtureError", "digest_bytes", "load_fixture"]

PROVENANCE_CLASSES: Final = frozenset(
    {
        "authored",
        "protocol-adversarial",
        "synthetic-mutation",
        "recorded-response",
        "external-corpus",
    }
)
MAX_FIXTURE_BYTES: Final = 8 * 1024 * 1024


class FixtureError(Exception):
    """A fixture is missing, too large, or does not declare its provenance."""


@dataclass(frozen=True, slots=True)
class Fixture:
    path: Path
    relative: str
    digest: str
    provenance: str
    data: Any

    def require(self, key: str) -> Any:
        if key not in self.data:
            raise FixtureError(f"{self.relative}: missing {key!r}")
        return self.data[key]


def digest_bytes(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def load_fixture(root: Path, relative: str) -> Fixture:
    """Load ``relative`` under ``root``, refusing to escape it.

    Fixture paths come from suite files, which are repository data — but a path
    that can climb out of the fixture tree is a path traversal whether or not
    today's inputs use it, and the harness reads whatever it is pointed at.
    """
    root = root.resolve()
    candidate = (root / relative).resolve()
    if candidate != root and root not in candidate.parents:
        raise FixtureError(f"{relative!r} escapes the fixture root")
    if not candidate.is_file():
        raise FixtureError(f"no fixture at {relative!r}")
    raw = candidate.read_bytes()
    if len(raw) > MAX_FIXTURE_BYTES:
        raise FixtureError(f"{relative!r} is {len(raw)} bytes; the limit is {MAX_FIXTURE_BYTES}")
    try:
        data = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise FixtureError(f"{relative!r}: {exc}") from exc

    provenance = _provenance(relative, data)
    return Fixture(
        path=candidate,
        relative=relative,
        digest=digest_bytes(raw),
        provenance=provenance,
        data=data,
    )


def _provenance(relative: str, data: Any) -> str:
    """Every fixture says where it came from; the shared protocol vectors are
    the one exception, and only because their own file documents them."""
    if not isinstance(data, dict):
        raise FixtureError(f"{relative!r}: a fixture is a JSON object")
    block = data.get("provenance")
    if block is None:
        if "vectors" in data and "description" in data:
            return "protocol-adversarial"
        raise FixtureError(f"{relative!r}: no provenance block; say where this data came from")
    if not isinstance(block, dict):
        raise FixtureError(f"{relative!r}: provenance must be a table")
    kind = block.get("class")
    if kind not in PROVENANCE_CLASSES:
        raise FixtureError(
            f"{relative!r}: provenance class {kind!r} is not one of {sorted(PROVENANCE_CLASSES)}"
        )
    if kind == "external-corpus":
        for key in ("source", "licence", "modification"):
            if not str(block.get(key, "")).strip():
                raise FixtureError(f"{relative!r}: external-corpus fixtures must record {key!r}")
    return str(kind)
