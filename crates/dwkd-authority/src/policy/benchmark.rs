//! The policy evaluation benchmark: the M3 target, measured.
//!
//! > **Acceptance:** policy p99 < 200 µs at 300 rules.
//! > — [ROADMAP.md](../../../../../docs/ROADMAP.md) M3,
//! >   [POLICY.md](../../../../../docs/POLICY.md) §4
//!
//! # What is measured
//!
//! ```text
//!     compiled policy + canonical action + typed context  ->  Decision
//! ```
//!
//! and nothing else. The policy is compiled before the clock starts, so TOML
//! parsing, schema walking and composition are all outside the figure. So are
//! file I/O, `kernel.db`, IPC, fsync, process start-up, resource resolution
//! and audit persistence — none of which exist in this milestone anyway, which
//! is precisely why the number has to say what it covers. Load time is
//! reported separately below, and is not mixed into the p99.
//!
//! # Why it is a unit test
//!
//! A realistic workload is path-heavy, and a canonical path can only be built
//! inside the crate ([ADR-0037]). Benchmarking over syntactic scopes alone
//! would measure a policy nobody ships.
//!
//! # Determinism
//!
//! The policy is **generated by a fixed function of an index**, not sampled:
//! there is no RNG here and therefore no seed to record. The same 300 rules
//! and the same action set are built on every run, on every machine.
//!
//! Run it with:
//!
//! ```console
//! $ make policy-benchmark
//! ```
//!
//! which runs this in release mode. A debug build measures the borrow checker's
//! idea of a good time, not the evaluator's, so the harness refuses to report a
//! verdict from one.
//!
//! [ADR-0037]: ../../../../../docs/adr/0037-capability-specifications-and-canonical-authority-identities.md

use core::fmt::Write as _;
use std::hint::black_box;
use std::time::{Duration, Instant};

use super::action::CanonicalAction;
use super::context::PolicyContext;
use super::rule::CompiledPolicy;
use super::testing::{
    anchors, executable_capability, interactive, path_capability, sandboxed, scheduled,
    syntactic_capability,
};
use super::{compose, evaluate, load};

/// The rule count the target is stated at.
const RULES: usize = 300;
/// Iterations discarded before measuring.
const WARMUP: usize = 20_000;
/// Iterations measured.
const SAMPLES: usize = 200_000;
/// The accepted target.
const TARGET: Duration = Duration::from_micros(200);

/// A 300-rule profile shaped like one somebody would deploy.
///
/// Three families in the proportions a real pack has: filesystem rules over
/// nested workspace paths, process rules over executable names, and network
/// rules over host patterns. Each rule is narrow enough that most actions miss
/// it, which is the case that costs — a policy whose first rule matches
/// everything would benchmark beautifully and mean nothing.
fn generated_source() -> String {
    let mut out = String::from("schema_version = 1\n\n[meta]\nname = \"bench\"\n");
    // Two of the 300 are written out below: the allowance and the default.
    for index in 0..RULES - 2 {
        let id = format!("r{index:04}");
        // `write!` into the buffer rather than `push_str(&format!(..))`: one
        // allocation instead of one per rule. Writing to a String cannot fail,
        // and the benchmark is not the place to pretend otherwise.
        let written = match index % 3 {
            0 => write!(
                out,
                "\n[[rule]]\nid = \"{id}\"\neffect = \"DENY\"\nreason = \"SENSITIVE_PATH\"\n\
                 when.verb = [\"fs.read\", \"fs.write\"]\n\
                 when.path_under = [\"${{WORKSPACE}}/vendor/pkg{index}\", \"/opt/pkg{index}\"]\n"
            ),
            1 => write!(
                out,
                "\n[[rule]]\nid = \"{id}\"\neffect = \"DENY\"\nreason = \"UNKNOWN_EXECUTABLE\"\n\
                 when.verb = \"process.exec\"\n\
                 when.executable_in = [\"tool{index}\", \"/usr/local/bin/tool{index}\"]\n\
                 when.environment = \"sandbox\"\n"
            ),
            _ => write!(
                out,
                "\n[[rule]]\nid = \"{id}\"\neffect = \"DENY\"\nreason = \"PROFILE_CEILING\"\n\
                 when.verb = [\"network.https\"]\n\
                 when.host_matches = [\"*.h{index}.example.com\", \"h{index}.example.net\"]\n"
            ),
        };
        if written.is_err() {
            unreachable!("writing to a String does not fail")
        }
    }
    // The one rule that permits, immediately before the default, so a
    // permitted action pays the full scan. Measuring only denials would
    // measure whichever branch happens to be cheaper.
    out.push_str(
        "\n[[rule]]\nid = \"allow-workspace\"\neffect = \"ALLOW\"\n\
         when.verb = [\"fs.read\", \"fs.write\"]\nwhen.path_under = \"${WORKSPACE}\"\n",
    );
    out.push_str(
        "\n[[postcondition]]\nid = \"unattended\"\neffect = \"DENY\"\n\
         reason = \"NO_HUMAN_AVAILABLE\"\n\
         when.provisional_effect = [\"REQUIRE_APPROVAL\"]\n\
         when.origin = [\"scheduled\"]\n",
    );
    out.push_str(
        "\n[[rule]]\nid = \"default\"\neffect = \"DENY\"\nreason = \"NO_MATCHING_RULE\"\n",
    );
    out
}

/// The actions measured, each exercising a different depth of the scan.
fn workload() -> Vec<(&'static str, CanonicalAction)> {
    vec![
        // Matches the first rule: the cheapest case.
        (
            "first-rule hit",
            sandboxed(path_capability(
                "fs.read",
                &["workspace", "vendor", "pkg0", "f"],
            )),
        ),
        // Matches nothing until the allowance, 299 rules down.
        (
            "full scan, allowed",
            sandboxed(path_capability(
                "fs.write",
                &["workspace", "src", "main.rs"],
            )),
        ),
        // Matches nothing at all: the whole scan plus the default.
        (
            "full scan, default deny",
            sandboxed(path_capability("fs.read", &["elsewhere", "file"])),
        ),
        // A process action, so every path rule is skipped on the verb.
        (
            "process, full scan",
            sandboxed(executable_capability(
                "process.exec",
                &["usr", "bin", "git"],
                7,
            )),
        ),
        // A host action: 100 label-aware wildcard comparisons.
        (
            "network, full scan",
            sandboxed(syntactic_capability("network.https:api.example.org")),
        ),
    ]
}

/// One measured series, sorted.
fn measure(
    policy: &CompiledPolicy,
    action: &CanonicalAction,
    context: &PolicyContext,
) -> Vec<Duration> {
    for _ in 0..WARMUP {
        black_box(evaluate(
            black_box(policy),
            black_box(action),
            black_box(context),
        ));
    }
    let mut samples = Vec::with_capacity(SAMPLES);
    for _ in 0..SAMPLES {
        let start = Instant::now();
        // `black_box` on the result as well as the arguments: the decision is
        // otherwise dead and a release build is entitled to delete the call.
        black_box(evaluate(
            black_box(policy),
            black_box(action),
            black_box(context),
        ));
        samples.push(start.elapsed());
    }
    samples.sort_unstable();
    samples
}

/// The value at a percentile of a sorted series.
///
/// Nearest-rank, truncating: p99 of 200 000 samples is index 197 998, the
/// 197 999th smallest. Truncating rather than interpolating makes the reported
/// figure a measurement that actually occurred rather than one between two.
#[expect(
    clippy::integer_division,
    reason = "nearest-rank percentiles are an index, which is an integer"
)]
fn percentile(sorted: &[Duration], percent: usize) -> Duration {
    let Some(last) = sorted.len().checked_sub(1) else {
        return Duration::ZERO;
    };
    sorted
        .get((last * percent) / 100)
        .copied()
        .unwrap_or_default()
}

#[test]
#[ignore = "evidence, not a merge gate: run with `make policy-benchmark`"]
fn policy_evaluation_meets_the_two_hundred_microsecond_target_at_three_hundred_rules() {
    let source = generated_source();
    let load_started = Instant::now();
    let Ok(profile) = load("bench.toml", &source) else {
        unreachable!("the generated policy must load")
    };
    let name = profile.name().clone();
    let Ok(policy) = compose(&name, &[profile]) else {
        unreachable!("the generated policy must compose")
    };
    let load_time = load_started.elapsed();
    assert_eq!(
        policy.rules().len(),
        RULES,
        "the workload must be 300 rules"
    );

    let context = interactive();
    let unattended = scheduled();

    println!("DireWolf policy evaluation benchmark");
    println!("------------------------------------------------------------");
    println!(
        "build profile:      {}",
        if cfg!(debug_assertions) {
            "debug"
        } else {
            "release"
        }
    );
    println!("rules:              {}", policy.rules().len());
    println!("postconditions:     {}", policy.postconditions().len());
    println!("warmup iterations:  {WARMUP}");
    println!("measured iterations:{SAMPLES}");
    println!("target:             p99 < {TARGET:?}");
    println!("source bytes:       {}", source.len());
    println!("load+compose:       {load_time:?}  (NOT part of the p99 below)");
    println!("anchors resolved:   {}", anchors().workspace.is_some());
    println!();
    println!(
        "{:<26} {:>10} {:>10} {:>10} {:>10} {:>12}",
        "workload", "p50", "p95", "p99", "max", "total"
    );

    let mut worst_p99 = Duration::ZERO;
    for (name, action) in workload() {
        let sorted = measure(&policy, &action, &context);
        let total: Duration = sorted.iter().sum();
        let (p50, p95, p99) = (
            percentile(&sorted, 50),
            percentile(&sorted, 95),
            percentile(&sorted, 99),
        );
        let max = sorted.last().copied().unwrap_or_default();
        println!("{name:<26} {p50:>10?} {p95:>10?} {p99:>10?} {max:>10?} {total:>12?}");
        worst_p99 = worst_p99.max(p99);
    }

    // The two-phase path, so the postcondition's cost is in the figure too.
    let approving = sandboxed(path_capability("fs.write", &["workspace", "src", "x"]));
    let sorted = measure(&policy, &approving, &unattended);
    let p99 = percentile(&sorted, 99);
    println!(
        "{:<26} {:>10?} {:>10?} {:>10?} {:>10?} {:>12?}",
        "unattended, two phases",
        percentile(&sorted, 50),
        percentile(&sorted, 95),
        p99,
        sorted.last().copied().unwrap_or_default(),
        sorted.iter().sum::<Duration>()
    );
    worst_p99 = worst_p99.max(p99);

    println!();
    println!("worst p99 across workloads: {worst_p99:?}");

    if cfg!(debug_assertions) {
        println!("VERDICT: not measured -- this is a debug build, so the number above is not");
        println!("         evidence of anything. Run `make policy-benchmark`.");
        return;
    }
    println!(
        "VERDICT: {} (worst p99 {worst_p99:?} against a target of {TARGET:?})",
        if worst_p99 < TARGET { "PASS" } else { "MISS" }
    );
    assert!(
        worst_p99 < TARGET,
        "policy evaluation p99 was {worst_p99:?}, over the {TARGET:?} target at {RULES} rules"
    );
}

#[test]
fn the_generated_benchmark_policy_is_the_size_it_claims() {
    // A merge gate, unlike the benchmark itself: if the generator drifts, the
    // evidence stops being about 300 rules and nobody notices, because the
    // benchmark only runs when somebody asks for it.
    let source = generated_source();
    let Ok(profile) = load("bench.toml", &source) else {
        unreachable!("the generated policy must load")
    };
    assert_eq!(profile.rules().len(), RULES);
    assert_eq!(profile.postconditions().len(), 1);
    assert!(
        workload().len() >= 5,
        "the workload must exercise more than one scan depth"
    );
    // And the workload really does reach different depths.
    let name = profile.name().clone();
    let Ok(policy) = compose(&name, &[profile]) else {
        unreachable!("composes")
    };
    let context = interactive();
    let hits: Vec<String> = workload()
        .iter()
        .map(|(_, action)| evaluate(&policy, action, &context).rule_id().to_string())
        .collect();
    assert!(hits.contains(&"r0000".to_owned()), "{hits:?}");
    assert!(hits.contains(&"allow-workspace".to_owned()), "{hits:?}");
    assert!(hits.contains(&"default".to_owned()), "{hits:?}");
}
